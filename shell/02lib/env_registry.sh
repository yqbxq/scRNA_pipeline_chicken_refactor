append_env_vars() {
  local spec
  local output_name
  local source_name
  local source_value

  for spec in "$@"; do
    output_name="${spec%%=*}"
    source_name="${spec#*=}"
    eval "source_value=\"\${${source_name}:-}\""
    ENV_ARGS+=("${output_name}=${source_value}")
  done
}
